import fs from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, "../..");
const dataDir = path.join(rootDir, "data", "academic-directory");
const reportPath = path.join(dataDir, "change-report.json");
const outputPath = path.join(dataDir, "sync-academic-units.sql");

function sqlLiteral(value) {
  if (value === null || value === undefined || value === "") return "null";
  return `'${String(value).replaceAll("'", "''")}'`;
}

function stagingInsert(row) {
  return `(${sqlLiteral(row.university_name)}, ${sqlLiteral(row.parent_name)}, ${sqlLiteral(row.unit_name)}, ${sqlLiteral(row.unit_type)}, ${sqlLiteral(row.source_url)})`;
}

function deactivateStatement(row) {
  return `update public.academic_units au\nset is_active = false, updated_at = now()\nfrom public.universities u\nwhere au.university_id = u.id\n  and lower(trim(u.name)) = lower(trim(${sqlLiteral(row.university_name)}))\n  and lower(trim(au.name)) = lower(trim(${sqlLiteral(row.unit_name)}))\n  and au.unit_type = ${sqlLiteral(row.unit_type)}\n  and au.parent_id is null\n  and au.is_active = true;`;
}

function typeChangeStatement(row) {
  return `update public.academic_units au\nset unit_type = ${sqlLiteral(row.current_unit_type)},\n    source_url = coalesce(${sqlLiteral(row.source_url)}, au.source_url),\n    updated_at = now()\nfrom public.universities u\nwhere au.university_id = u.id\n  and lower(trim(u.name)) = lower(trim(${sqlLiteral(row.university_name)}))\n  and lower(trim(au.name)) = lower(trim(${sqlLiteral(row.unit_name)}))\n  and au.unit_type = ${sqlLiteral(row.previous_unit_type)}\n  and au.parent_id is null;`;
}

async function main() {
  const report = JSON.parse(await fs.readFile(reportPath, "utf8"));
  const lines = [
    "-- Generated by scripts/academic-directory/generate-sync-sql.mjs",
    "-- Review this file before executing it in Supabase.",
    "begin;",
    "",
  ];

  if (report.added?.length) {
    lines.push(
      "-- New or reactivated academic units",
      "insert into public.academic_unit_import_staging",
      "  (university_name, parent_name, unit_name, unit_type, source_url)",
      "values",
      report.added.map((row) => `  ${stagingInsert(row)}`).join(",\n"),
      "on conflict do nothing;",
      "",
      "select * from public.import_academic_units();",
      ""
    );
  } else {
    lines.push("-- No additions detected.", "");
  }

  if (report.typeChanged?.length) {
    lines.push("-- Unit type changes", ...report.typeChanged.map(typeChangeStatement), "");
  } else {
    lines.push("-- No unit type changes detected.", "");
  }

  if (report.removed?.length) {
    lines.push(
      "-- Removed units are never deleted. Review before running these deactivations.",
      ...report.removed.map(deactivateStatement),
      ""
    );
  } else {
    lines.push("-- No removals detected.", "");
  }

  lines.push(
    "-- Inspect affected rows before replacing ROLLBACK with COMMIT.",
    "rollback;",
    ""
  );

  await fs.mkdir(dataDir, { recursive: true });
  await fs.writeFile(outputPath, lines.join("\n"), "utf8");

  console.log(
    `Generated sync SQL: +${report.addedCount ?? 0} -${report.removedCount ?? 0} ~${report.typeChangedCount ?? 0}`
  );
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
